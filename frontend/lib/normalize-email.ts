// Единственное место, которое приводит email к каноничному виду перед
// записью в User.email. Причина существования этого файла — I-1
// финального ревью ветки foundation: уникальность email в БД
// регистронезависима (миграция user_email_case_insensitive,
// CREATE UNIQUE INDEX ... (LOWER(email))), а better-auth ищет
// пользователя при входе строго через email.toLowerCase() + точное
// сравнение (better-auth/dist/db/internal-adapter.mjs). Если строка
// с заглавной буквой всё-таки попадёт в User.email, такой пользователь
// не сможет войти никогда — поиск её просто не найдёт. Один общий
// хелпер вместо normalize-на-каждом-вызывающем гарантирует, что новый
// код, создающий пользователей (следующий план — раздел «пользователи»),
// не сможет случайно забыть привести email к нижнему регистру.
export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase()
}
