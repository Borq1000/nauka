-- I-1 (финальное ревью feat/foundation): обычный уникальный индекс от
-- `email String @unique` (User_email_key) в PostgreSQL регистрозависим,
-- поэтому "owner@site.ru" и "Owner@site.ru" могут существовать одновременно
-- как два разных пользователя — а требование (ТЗ §4.5) прямо говорит
-- "email с уникальностью без учёта регистра". Хуже нарушения буквы
-- требования: better-auth ищет пользователя при входе через
-- email.toLowerCase() и точное сравнение (internal-adapter.mjs), поэтому
-- любая строка User с заглавной буквой в email не найдётся при входе
-- никогда — без единого следа в логах или в БД.
--
-- Функциональный индекс по LOWER(email) невыразим в schema.prisma (Prisma
-- не поддерживает индексы по выражениям), поэтому — как и для
-- Page_isHome_unique — он написан руками, а не сгенерирован. Старый
-- индекс User_email_key НЕ удаляется: он остаётся дополнительной защитой
-- на уровне обычного равенства строк и тем, на что ссылается @unique в
-- schema.prisma.
CREATE UNIQUE INDEX "User_email_lower_key" ON "User" (LOWER("email"));
