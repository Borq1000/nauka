import 'server-only'
import { redirect } from 'next/navigation'
import { AuthError } from './session'

/**
 * Превращает AuthError, брошенный requireUser()/requireRole(), в подходящую
 * реакцию Server Action. Без этого необработанный AuthError в проде заменяется
 * Next на общую ошибку с digest (см. Task 6 brief) — русский текст сообщения
 * никуда не долетает, а вместо перенаправления на вход визитёр видит страницу
 * ошибки.
 *
 * UNAUTHENTICATED и INACTIVE ведут на страницу входа: в обоих случаях у
 * вызывающего нет рабочей сессии (отключённый пользователь неотличим от
 * невошедшего для всего, что стоит после getSessionUser/requireUser — см.
 * комментарий в session.ts), и /admin/login — ровно то место, куда его нужно
 * отправить.
 *
 * FORBIDDEN — другой случай: пользователь аутентифицирован и активен, но его
 * роль не удовлетворяет требованию. Отправлять его на форму входа было бы
 * неверно (он уже вошёл под собственной учётной записью) и вводило бы в
 * заблуждение — редирект намекнул бы, что проблема в самом входе. Поэтому
 * FORBIDDEN не перехватывается здесь и просто перебрасывается дальше:
 * решение, что показать вместо этого (сообщение в форме, отдельная страница
 * «Доступ запрещён»), — забота конкретного раздела админки, а такие разделы
 * появятся только со следующим планом. Строить экран для кода, у которого
 * сегодня нет ни одного вызывающего, было бы работой за пределами этой задачи.
 */
export function handleAuthError(error: unknown): never {
  if (error instanceof AuthError && (error.code === 'UNAUTHENTICATED' || error.code === 'INACTIVE')) {
    redirect('/admin/login')
  }
  throw error
}
